    /*
    * @brief Computes the index of a look-up given the blocker configuration. 
    * Note: Bit board - LSB = A1, MSB = H8.
    * @param blockerConfig: Bit board of all pieces in the path of the piece.
    * @param squareIndex:   Index of a square in a bit board [0, 63].
    * @param pieceType:     Type of the piece specifying the look-up.
    * @return look-up index
    */
    inline int get_lookup_index(const uint64_t blockerConfig, const int squareIndex, const core::PieceType pieceType) {
        switch (pieceType)
        {
        case core::PieceType::Bishop:  return (int)((blockerConfig * bishopMagics[squareIndex]) >> 53);
        case core::PieceType::Rook:    return (int)((blockerConfig * rookMagics[squareIndex]) >> 50);
        default: return -1;
        }
    }

    static inline int get_lookup_index(const uint64_t blockerConfig, const uint64_t magicNumber, const int shift) {
        return (int)((blockerConfig * magicNumber) >> shift);
    }
