    /*
    * @brief Returns a movement mask assuming an empty board. Note: Returns zero if a pawn.
    * @param pieceType:     Type of piece specifying mask.
    * @param squareIndex:   Index of square in a bit board [0, 63].
    * @return movement mask
    */
    constexpr inline uint64_t get_mask(core::PieceType pieceType, unsigned int squareIndex) {
        if (pieceType == core::PieceType::Pawn) return 0;

        switch (pieceType)
        {
        case core::PieceType::Knight:  return KNIGHT_MASKS[squareIndex];
        case core::PieceType::Bishop:  return BISHOP_MASKS[squareIndex];
        case core::PieceType::Rook:    return ROOK_MASKS[squareIndex];
        case core::PieceType::Queen:   return QUEEN_MASKS[squareIndex];
        case core::PieceType::King:    return KING_MASKS[squareIndex];
        default:                        return 0;
        }
    }


    /*
    * @brief Returns a pawn movement mask given where all and enemy pieces are, and whether it's attacking.
    * @param color:         Color of pawns.
    * @param squareIndex:   Index of square in a bit board [0, 63].
    * @param allPieces:     Bit board of all pieces.
    * @param enemyPieces:   Bit board of enemy pieces.
    * @param attacking:     True if the pawn is attacking.
    * @return movement mask
    */
    constexpr inline uint64_t get_pawn_mask(core::Color color, unsigned int squareIndex, uint64_t allPieces, uint64_t enemyPieces, bool attacking) {
        switch (color)
        {
        case core::Color::White: return attacking ? 
            WHITE_PAWN_ATTACKS[squareIndex] & enemyPieces : 
            (core::bit_board::square_to_bit_board(squareIndex) << 8 & ~allPieces) | core::bit_board::square_to_bit_board(squareIndex) << 16 & ~allPieces & core::bit_board::FOURTH_RANK;
        case core::Color::Black: return attacking ? 
            BLACK_PAWN_ATTACKS[squareIndex] & enemyPieces : 
            (core::bit_board::square_to_bit_board(squareIndex) >> 8 & ~allPieces) | core::bit_board::square_to_bit_board(squareIndex) >> 16 & ~allPieces & core::bit_board::FIFTH_RANK;
        default: return 0;
        }
    }
